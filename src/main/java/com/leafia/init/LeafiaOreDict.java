package com.leafia.init;

import static com.hbm.inventory.OreDictManager.*;
import static com.hbm.inventory.material.MaterialShapes.*;
import static com.leafia.init.recipes.LeafiaRecipeInjector.leafiaItem;
import static com.leafia.init.recipes.LeafiaRecipeInjector.res;

import com.hbm.blocks.ModBlocks;
import com.hbm.items.ModItems;
import com.hbm.inventory.OreDictManager;
import com.hbm.inventory.OreDictManager.DictFrame;
import com.hbm.inventory.OreDictManager.DictGroup;

/**
 * The addon's ore-dictionary frames, so a recipe written {@code FSALLOY.ingot()} reads the same here
 * as upstream (GENERATED by a script from {@code AddonOreDict}).
 *
 * <p>A frame is only a name: {@code new DictFrame("Fissite").ingot()} is {@code ingotFissite}, which the
 * base mod's {@code OreDictStack} resolves to the tag {@code c:ingots/fissite}. Which items are in that
 * tag is the generators' job (a generator script for the addon's own items, D-1085;
 * a generator script for the autogen plates, the group tags and the registrations that name base
 * items, D-3026) - so the upstream registrations ({@code FSALLOY.ingot(Resources.ingot_fissite)}) are not
 * repeated here.
 *
 * <p>The groups are: {@code AddonOreDict.registerGroups()} (a group of the addon's own, and the base
 * mod's {@code ANY_RESISTANTALLOY} gaining the taintium steel, which upstream does from
 * {@code MixinOreDictManager} when the base builds the group). {@link #registerGroups()} runs from the mod
 * constructor, before the base mod's own {@code registerGroups()} in common setup spreads the group over its
 * shapes, so the re-registration table sees the new member.
 */
public final class LeafiaOreDict {

	private LeafiaOreDict() {}

	public static final DictFrame K = new DictFrame("Potassium");
	public static final DictFrame RB = new DictFrame("Rubidium");
	public static final DictFrame FR = new DictFrame("Francium");
	public static final DictFrame XN = new DictFrame("Xanaxium");
	public static final DictFrame NC279 = new DictFrame("Nc279");
	public static final DictFrame NC273 = new DictFrame("Nc273");
	public static final DictFrame NC269 = new DictFrame("Nc269");
	public static final DictFrame TN = new DictFrame("Taintium");
	public static final DictFrame TNALLOY = new DictFrame("TnAlloy");
	public static final DictFrame MYSTICITE = new DictFrame("Mysticite");
	public static final DictFrame CH = new DictFrame("Chydalium");
	public static final DictFrame FS = new DictFrame("Fissium");
	public static final DictFrame FSALLOY = new DictFrame("Fissite");
	public static final DictFrame CORIUM = new DictFrame("Corium");
	public static final DictFrame ZETA = new DictFrame("Zetalite");
	public static final DictFrame CHERNOBYL = new DictFrame("Chernobylite");
	public static final DictFrame MANA = new DictFrame("Mana");
	public static final DictGroup ANY_ULTRAALLOY = new DictGroup("AnyUltraAlloy", MYSTICITE);

	/**
	 * NTM-CE's {@code OreDictManager.getReflector()}: the ore name of the neutron reflector plate. The 1.7.10 base mod has no
	 * such plate (its reflector is the item {@code neutron_reflector}), so the addon registers one, {@code plate_tungsten_carbide},
	 * in the tag this names (D-3026).
	 */
	public static String getReflector() { return OreDictManager.WC.plate(); }

	private static boolean groupsRegistered;

	/** Upstream's {@code registerGroups()}, plus the redirect that joins the base mod's group. Once. */
	public static synchronized void registerGroups() {
		if(groupsRegistered) return;
		groupsRegistered = true;
		OreDictManager.ANY_RESISTANTALLOY.addFrames(TNALLOY);
		ANY_ULTRAALLOY.addPrefix(INGOT,true).addPrefix(LIGHTRECEIVER,true).addPrefix(PLATE,true);
	}

	private static boolean oresRegistered;

	/**
	 * Upstream's {@code registerOres()}: the addon's items under their ore names, in the base mod's own binding table
	 * ({@code OreDictManager.ORE_BINDINGS}), which is what {@code namesOf} reads - and so {@code Mats.getMaterialsFromItem}, the
	 * crucible, the arc furnace and the anvil's name guards. A recipe's ingredient is a tag and these are not needed for it
	 * (the generators write the same names as tags); a smelter asking what an ingot is made of is the question this answers.
	 * Upstream runs it from {@code MixinOreDictManager} at the head of the base's {@code registerOres}, after the base's
	 * {@code registerGroups}; the base's runs from an enqueued common-setup task, so this one runs from the addon's own
	 * (not enqueued) handler of the same event, which is before it, and calls the base's {@code registerGroups} first (a set,
	 * so the base's second call changes nothing). Once.
	 */
	public static synchronized void registerOres() {
		if(oresRegistered) return;
		oresRegistered = true;
		OreDictManager.registerGroups();
		registerGroups();
		K.ingot(res("ingot_potassium"));
		RB.ingot(res("ingot_rubidium"));
		FR.ingot(res("ingot_francium"));
		SRN.nugget(res("nugget_schraranium"));
		OSMIRIDIUM.dust(leafiaItem("powder_osmiridium"));
		XN.ingot(res("ingot_xanaxium")).dust(res("powder_xanaxium"));
		CORIUM.block(ModBlocks.block_corium.get());
		CORIUM.block(ModBlocks.block_corium_cobble.get());
		CHERNOBYL.ore(leafiaItem("ore_corium_chernobylite"));
		ZETA.ore(leafiaItem("ore_corium_zetalite"));
		MANA.dust(ModItems.powder_magic.get());
		NC279.ingot(res("ingot_nc279"));
		NC279.dust(res("powder_nc279"));
		NC279.billet(res("billet_nc279"));
		TN.ingot(res("ingot_taintium"));
		TN.dust(res("powder_taintium"));
		FS.ingot(res("ingot_fissium"));
		FS.billet(res("billet_fissium"));
		FSALLOY.ingot(res("ingot_fissite"));
		FSALLOY.plate(res("plate_fissite"));
		MYSTICITE.ingot(res("ingot_mysticite"));
		MYSTICITE.plate(res("plate_mysticite"));
		TNALLOY.ingot(res("ingot_tnalloy"));
		ANY_RESISTANTALLOY.addFrames(TNALLOY);
		CH.ingot(res("ingot_chydalium"));
		CH.dust(res("powder_chydalium"));
		CH.billet(res("billet_chydalium"));
	}
}
