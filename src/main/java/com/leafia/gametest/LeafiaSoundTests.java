package com.leafia.gametest;

import java.util.Set;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.leafia.init.LeafiaSounds;
import com.leafia.lib.LeafiaRef;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.gametest.framework.GameTest;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.sounds.SoundSource;
import net.neoforged.neoforge.gametest.GameTestHolder;
import net.neoforged.neoforge.gametest.PrefixGameTestTemplate;

/**
 * The addon's sound layer — 98 events over 137 .ogg files, generated by
 * a script.
 *
 * <p>Nothing plays most of these yet; they landed because the elevator chips need seven of them
 * and generating the whole layer costs the same as generating seven. So these tests pin the
 * things that break silently in a generated layer: an event registering under the wrong id, a
 * sound landing in the wrong mixer channel, and the subtitle keys going missing.
 */
@GameTestHolder(LeafiaRef.MODID)
@PrefixGameTestTemplate(false)
public class LeafiaSoundTests {

	private static final String EMPTY = "empty";

	/** Everything the generator emitted is actually in the registry, under the addon. */
	@GameTest(template = EMPTY)
	public static void theSoundsAreRegisteredUnderTheAddon(GameTestHelper helper) {

		int count = 0;
		for(ResourceLocation id : BuiltInRegistries.SOUND_EVENT.keySet()) {
			if(id.getNamespace().equals(LeafiaRef.MODID)) count++;
		}

		// 98 of upstream's, upstream's later music.bgm013_50 and NTM-CE's block.rbmklid (D-3018).
		helper.assertTrue(count == 100,
				"the generator emits 100 events; the registry has " + count);

		helper.succeed();
	}

	/**
	 * The seven the elevator chips reach for, by the exact upstream key.
	 *
	 * <p>These are the reason the layer landed now rather than later, and a renamed key would not
	 * fail a compile — {@code LeafiaSounds} is generated, so the field would simply vanish and the
	 * chip would fail to build against a name nobody had noticed changing.
	 */
	@GameTest(template = EMPTY)
	public static void theSevenSoundsTheElevatorNeedsExist(GameTestHelper helper) {

		assertSound(helper, LeafiaSounds.skyliftarrive, "elevators.skyliftarrive");
		assertSound(helper, LeafiaSounds.electronicpingshort, "elevators.electronicpingshort");
		assertSound(helper, LeafiaSounds.elevator_jam_loop, "music.lsplash.elevator_jam.loop");
		assertSound(helper, LeafiaSounds.elevator_jam_end, "music.lsplash.elevator_jam.end");
		assertSound(helper, LeafiaSounds.local_forecast, "music.incompetech.local_forecast");

		helper.succeed();
	}

	private static void assertSound(GameTestHelper helper,
			net.neoforged.neoforge.registries.DeferredHolder<SoundEvent, SoundEvent> holder,
			String key) {

		ResourceLocation id = BuiltInRegistries.SOUND_EVENT.getKey(holder.get());
		helper.assertTrue(id != null, key + " is not in the registry at all");
		helper.assertTrue(id.getPath().equals(key),
				"expected the key " + key + ", got " + id.getPath());
	}

	/**
	 * The mixer channel, which moved out of sounds.json.
	 *
	 * <p>1.21.1 takes a {@link SoundSource} at the play site, so upstream's per-entry category
	 * became {@link LeafiaSounds#sourceOf}. That mapping is the part a translation gets wrong
	 * silently: 1.12.2 writes {@code "category": "block"} and the 1.21.1 constant is
	 * {@code BLOCKS}, plural — a mismatch the generator now asserts on, and which put every one of
	 * these in the wrong channel on the first run.
	 */
	@GameTest(template = EMPTY)
	public static void theMixerChannelSurvivedTheMove(GameTestHelper helper) {

		helper.assertTrue(LeafiaSounds.sourceOf("elevators.skyliftarrive") == SoundSource.BLOCKS,
				"a lift arriving is a block sound, got "
						+ LeafiaSounds.sourceOf("elevators.skyliftarrive"));
		helper.assertTrue(LeafiaSounds.sourceOf("music.incompetech.local_forecast") == SoundSource.MUSIC,
				"cabin music is filed under music, got "
						+ LeafiaSounds.sourceOf("music.incompetech.local_forecast"));
		helper.assertTrue(LeafiaSounds.sourceOf("weapon.mukeexplosion") == SoundSource.PLAYERS,
				"upstream files the muke under player, got "
						+ LeafiaSounds.sourceOf("weapon.mukeexplosion"));

		// An unknown key must not throw - upstream plays a few sounds by name that are not its own.
		helper.assertTrue(LeafiaSounds.sourceOf("not.a.real.sound") == SoundSource.MASTER,
				"an unknown key falls back to MASTER");

		helper.succeed();
	}

	/**
	 * Upstream's four dead registrations stayed dead.
	 *
	 * <p>{@code block.assembler_start}, {@code _stop}, {@code _strike} and {@code block.motor} are
	 * registered by upstream's {@code LeafiaSoundEvents} and have no .ogg, no sounds.json entry and
	 * no consumer anywhere in the clone. Carrying them would put four events in the registry with
	 * nothing behind them. See D-1038.
	 */
	@GameTest(template = EMPTY)
	public static void theFourDeadRegistrationsAreNotCarried(GameTestHelper helper) {

		for(String dead : new String[]{"block.assembler_start", "block.assembler_stop",
				"block.assembler_strike", "block.motor"}) {

			ResourceLocation id = ResourceLocation.fromNamespaceAndPath(LeafiaRef.MODID, dead);
			helper.assertTrue(!BuiltInRegistries.SOUND_EVENT.containsKey(id),
					dead + " has no sound behind it upstream and must not be registered");
		}

		helper.succeed();
	}

	/**
	 * Every subtitle key {@code sounds.json} names resolves, and nothing in the lang file is
	 * unreferenced.
	 *
	 * <p><b>The class comment claimed this coverage for four batches and no test provided it.</b>
	 * The generator wrote one {@code subtitles.leafia.<key>} row per sounds.json entry, which is
	 * right only for the entries that have no subtitle of their own; upstream gives 22 of its 100 a
	 * key like {@code subtitles.block.az5}, so the generator wrote 22 rows nothing referenced and
	 * left the 22 that <em>were</em> referenced undefined. 31 {@code Missing subtitle translation}
	 * ERRORs on every client start, found by D-1043's sweep. Both halves were generated from the
	 * same wrong premise, so the generator's own {@code --check} could not see it — which is the
	 * argument for asserting the <em>relationship between two files</em> rather than either file's
	 * shape. See D-1044.
	 *
	 * <p>The second half matters as much as the first: an unreferenced row is exactly what the bug
	 * left behind, and nothing at runtime ever complains about one.
	 */
	@GameTest(template = EMPTY)
	public static void everySubtitleKeyResolvesAndNothingIsOrphaned(GameTestHelper helper) {

		JsonObject sounds = readJson(helper, "/assets/leafia/sounds.json");
		JsonObject lang = readJson(helper, "/assets/leafia/lang/en_us.json");

		Set<String> referenced = new java.util.TreeSet<>();
		for(String event : sounds.keySet()) {
			JsonObject entry = sounds.getAsJsonObject(event);
			helper.assertTrue(entry.has("subtitle"),
					event + " has no subtitle, so 1.21.1 logs an ERROR for it every reload");
			referenced.add(entry.get("subtitle").getAsString());
		}

		Set<String> defined = new java.util.TreeSet<>();
		for(String key : lang.keySet())
			if(key.startsWith("subtitles.")) defined.add(key);

		Set<String> unresolved = new java.util.TreeSet<>(referenced);
		unresolved.removeAll(defined);
		// Upstream reuses one vanilla key, and the addon must NOT define it: a mod lang row for a
		// vanilla key overrides vanilla's own wording for the whole game. Confirmed by the sweep
		// rather than assumed - it named 23 missing keys and this was not among them, because it
		// resolved against vanilla's en_us.json.
		unresolved.remove("subtitles.weather.rain");

		Set<String> orphaned = new java.util.TreeSet<>(defined);
		orphaned.removeAll(referenced);

		// Both lists, in one assert. A fail-fast check here would report the first unresolved key
		// and hide the orphans entirely, and the orphans are the half that explains the cause.
		helper.assertTrue(unresolved.isEmpty() && orphaned.isEmpty(),
				unresolved.size() + " subtitle key(s) nothing translates: " + unresolved
						+ "; " + orphaned.size() + " lang row(s) nothing references: " + orphaned);
		helper.succeed();
	}

	/**
	 * Every file the addon's {@code sounds.json} names is shipped (the addon's twin of the base mod's
	 * {@code SoundTests.everySoundFileExists}).
	 *
	 * <p>Upstream's file names four that nobody ships, upstream included ({@code entity/slicer3},
	 * {@code weapon/hit_metal0}, {@code music/422fgame}, {@code music/422fmenu}), which the client warned about on
	 * every resource load. The generator drops them (D-3051), which leaves {@code item.pointed} and the two music
	 * events with an empty list - silent, as upstream's were - and this pins both halves: nothing names a missing
	 * file, and exactly those three events are the empty ones.
	 */
	@GameTest(template = EMPTY)
	public static void everySoundFileTheAddonNamesIsShipped(GameTestHelper helper) {

		JsonObject sounds = readJson(helper, "/assets/leafia/sounds.json");

		java.util.List<String> missing = new java.util.ArrayList<>();
		Set<String> silent = new java.util.TreeSet<>();
		for(String event : sounds.keySet()) {
			com.google.gson.JsonArray list = sounds.getAsJsonObject(event).getAsJsonArray("sounds");
			if(list.isEmpty()) silent.add(event);
			for(com.google.gson.JsonElement sound : list) {
				String name = sound.isJsonObject() ? sound.getAsJsonObject().get("name").getAsString() : sound.getAsString();
				int colon = name.indexOf(':');
				String namespace = colon < 0 ? "minecraft" : name.substring(0, colon);
				if(!namespace.equals(LeafiaRef.MODID)) continue;
				String path = "/assets/" + namespace + "/sounds/" + name.substring(colon + 1) + ".ogg";
				if(LeafiaSoundTests.class.getResource(path) == null) missing.add(event + " -> " + name);
			}
		}

		helper.assertTrue(missing.isEmpty(), missing.size() + " sound file(s) sounds.json names are not shipped: " + missing);
		helper.assertTrue(silent.equals(Set.of("item.pointed", "music.422fgame", "music.422fmenu")),
				"the events with nothing to play are the three whose files nobody ships, found " + silent);
		helper.succeed();
	}

	private static JsonObject readJson(GameTestHelper helper, String path) {
		try(java.io.InputStream in = LeafiaSoundTests.class.getResourceAsStream(path)) {
			helper.assertTrue(in != null, "missing resource: " + path);
			return JsonParser.parseString(new String(in.readAllBytes(),
					java.nio.charset.StandardCharsets.UTF_8)).getAsJsonObject();
		} catch(java.io.IOException e) {
			helper.fail("could not read " + path + ": " + e);
			return null;
		}
	}
}
