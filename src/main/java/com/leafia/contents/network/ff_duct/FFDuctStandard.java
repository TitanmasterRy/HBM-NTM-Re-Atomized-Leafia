/**
 * {@code ff_duct}, upstream's "Special Pipe": the duct Forge fluids travel in, in the base duct's
 * three finishes.
 *
 * <p>Upstream: {@code com/leafia/contents/network/ff_duct/FFDuctStandard.java}, 520 lines of which
 * most is 1.12.2 model baking. What is left is the connection rule, the shapes and the overlay.
 *
 * <h2>Connections are blockstate</h2>
 *
 * Upstream decides what a duct joins in {@code getActualState}, every time it is drawn. Here the
 * six booleans are stored ({@link PipeBlock}'s, as the base duct's) and recomputed when a
 * neighbour changes, when the duct is placed and when its fluid changes. A side connects when
 * {@link LeafiaUtil#canConnectFF} says so - a duct of the same fluid, or a machine that is an
 * {@link IFFHandler} with a fluid handler on that side - or, upstream's second branch, when the
 * neighbour (or the core behind a proxy) is an {@code IFFHandler} exposing any tank at all. In
 * 1.12.2 that branch looked for a tank that could fill or drain, and every {@code FluidTank} said
 * both, so "any tank" is the same test.
 *
 * <h2>Two "end" flags, not six</h2>
 *
 * Upstream's model draws a flanged end ({@code pX}) or a plain run ({@code pXf}) on each side of a
 * straight duct, depending on whether the neighbour there is a duct of the same fluid
 * ({@code isEnd}); it computes all six flags and reads only the two on the duct's own axis, and only
 * when the duct is straight. Storing all six would be 12,288 states for three finishes; storing the
 * two that are read, {@link #END_POS} (east, up or south) and {@link #END_NEG}, is 768, and the
 * model reads exactly what it read before. They are false whenever the duct is not straight. The
 * model itself is generated by a script, which checks its multipart
 * against upstream's {@code FFDuctBakedModel.buildWorldQuads} over every state.
 *
 * <h2>The rest</h2>
 *
 * <ul>
 * <li>{@code ItemBlockSpecialAABB} with {@code IBlockSpecialPlacementAABB}: CE let a duct be placed
 *     into a space an entity stands in, testing only the shape it would have. A 1.21.1 block item
 *     already tests the placement state's own collision shape, so the item is the base mod's
 *     per-finish {@code ItemBlockBase.Variant}.</li>
 * <li>The outline is upstream's single box ({@code getBoundingBox}); the collision is upstream's
 *     list of boxes ({@code addCollisionBoxToList}), which is the base duct's
 *     {@link FluidDuctStandard#shapeFor} exactly.</li>
 * <li>The pick ({@code getPickBlock}) is <b>the base mod's fluid duct item</b> of the duct's
 *     fluid, not this block: upstream's own "TODO: fix ts". Kept (D-021).</li>
 * </ul>
 */
public class FFDuctStandard extends FFDuctBase implements IBlockMulti<PipeMaterial>, ILookOverlay {

	public static final EnumProperty<PipeMaterial> MATERIAL = FluidDuctStandard.MATERIAL;

	public static final BooleanProperty DOWN = PipeBlock.DOWN;
	public static final BooleanProperty UP = PipeBlock.UP;
	public static final BooleanProperty NORTH = PipeBlock.NORTH;
	public static final BooleanProperty SOUTH = PipeBlock.SOUTH;
	public static final BooleanProperty WEST = PipeBlock.WEST;
	public static final BooleanProperty EAST = PipeBlock.EAST;
	public static final Map<Direction, BooleanProperty> BY_DIRECTION = PipeBlock.PROPERTY_BY_DIRECTION;

	/** On a straight duct: the east, up or south neighbour is not a duct of the same fluid. */
	public static final BooleanProperty END_POS = BooleanProperty.create("endpos");
	/** On a straight duct: the west, down or north neighbour is not a duct of the same fluid. */
	public static final BooleanProperty END_NEG = BooleanProperty.create("endneg");

	private static final VoxelShape[] OUTLINES = new VoxelShape[64];
	static {
		for(int mask = 0; mask < 64; mask++) OUTLINES[mask] = outlineFor(mask);
	}

	public FFDuctStandard(Properties properties) {
		super(properties);
		BlockState base = getStateDefinition().any().setValue(MATERIAL, PipeMaterial.NEO)
				.setValue(END_POS, false).setValue(END_NEG, false);
		for(BooleanProperty p : BY_DIRECTION.values()) base = base.setValue(p, false);
		registerDefaultState(base);
	}

	@Override
	protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
		builder.add(MATERIAL, DOWN, UP, NORTH, SOUTH, WEST, EAST, END_POS, END_NEG);
	}

	@Override
	public EnumProperty<PipeMaterial> getVariantProperty() {
		return MATERIAL;
	}

	/** Upstream names all three finishes {@code tile.ff_duct.name}. */
	@Override
	public String getDescriptionId(PipeMaterial variant) {
		return getDescriptionId();
	}

	/// CONNECTIONS ///

	private static FluidType typeAt(BlockGetter level, BlockPos pos) {
		return level.getBlockEntity(pos) instanceof FFDuctTE duct ? duct.getFluidType() : Fluids.NONE;
	}

	/** Upstream's {@code canConnectTo}: whether this duct joins whatever is on {@code dir}. */
	public static boolean canConnectTo(BlockGetter world, BlockPos pos, Direction dir, FluidType type) {
		BlockPos neighborPos = pos.relative(dir);
		if(LeafiaUtil.canConnectFF(world, neighborPos, type, dir.getOpposite())) {
			return true;
		}
		BlockEntity neighbor = world.getBlockEntity(neighborPos);
		if(neighbor != null && !neighbor.isRemoved() && world instanceof Level level) {
			IFluidHandler handler = level.getCapability(Capabilities.FluidHandler.BLOCK, neighborPos, neighbor.getBlockState(),
					neighbor, dir.getOpposite());
			if(handler != null) {
				BlockEntity mainTE = neighbor;
				if(neighbor instanceof BlockEntityProxyBase proxy)
					mainTE = proxy.getCore();
				if(mainTE instanceof IFFHandler) {
					// Upstream walks the tank properties for one that can fill or drain, and is true
					// when there are none; a 1.12.2 FluidTank answers both, so every handler passes.
					return true;
				}
			}
		}
		return false;
	}

	/** Upstream's {@code isEnd}: the neighbour on {@code dir} is not a duct of this fluid. */
	public static boolean isEnd(BlockGetter world, BlockPos pos, Direction dir, FluidType type) {
		return !(world.getBlockEntity(pos.relative(dir)) instanceof FFDuctTE duct && duct.getFluidType() == type);
	}

	/** Upstream's six-bit mask: east 32, west 16, up 8, down 4, south 2, north 1. The base duct's. */
	public static int mask(BlockState state) {
		return FluidDuctStandard.mask(state);
	}

	/** The side test {@link #connect(BlockState, BlockGetter, BlockPos, SideTest)} asks: {@link #canConnectTo}'s own signature. */
	@FunctionalInterface
	public interface SideTest {
		boolean canConnect(BlockGetter world, BlockPos pos, Direction dir, FluidType type);
	}

	private static BlockState connect(BlockState state, BlockGetter level, BlockPos pos) {
		return connect(state, level, pos, FFDuctStandard::canConnectTo);
	}

	/**
	 * The six arms and the two end flags a duct at {@code pos} draws, against any {@link BlockGetter} and with the side test the
	 * caller chooses. The world uses {@link #canConnectTo}; the guide scenes' jar (D-3029) adds its stand-in machine, which a jar
	 * cannot expose a capability for.
	 */
	public static BlockState connect(BlockState state, BlockGetter level, BlockPos pos, SideTest test) {
		FluidType type = typeAt(level, pos);
		for(Direction dir : Direction.values())
			state = state.setValue(BY_DIRECTION.get(dir), test.canConnect(level, pos, dir, type));

		int mask = mask(state);
		boolean endPos = false, endNeg = false;
		Direction pos1 = null, neg1 = null;
		if(mask != 0) {
			if((mask & 0b001111) == 0) { pos1 = Direction.EAST; neg1 = Direction.WEST; }
			else if((mask & 0b110011) == 0) { pos1 = Direction.UP; neg1 = Direction.DOWN; }
			else if((mask & 0b111100) == 0) { pos1 = Direction.SOUTH; neg1 = Direction.NORTH; }
		}
		if(pos1 != null) {
			endPos = isEnd(level, pos, pos1, type);
			endNeg = isEnd(level, pos, neg1, type);
		}
		return state.setValue(END_POS, endPos).setValue(END_NEG, endNeg);
	}

	@Override
	public BlockState getStateForPlacement(BlockPlaceContext context) {
		return connect(defaultBlockState(), context.getLevel(), context.getClickedPos());
	}

	@Override
	protected BlockState updateShape(BlockState state, Direction direction, BlockState neighborState,
			LevelAccessor level, BlockPos pos, BlockPos neighborPos) {
		return connect(state, level, pos);
	}

	@Override
	protected void onPlace(BlockState state, Level level, BlockPos pos, BlockState oldState, boolean movedByPiston) {
		super.onPlace(state, level, pos, oldState, movedByPiston);
		if(level.isClientSide) return;
		BlockState updated = connect(state, level, pos);
		if(updated != state) level.setBlock(pos, updated, Block.UPDATE_CLIENTS);
	}

	@Override
	protected void neighborChanged(BlockState state, Level level, BlockPos pos, Block neighborBlock,
			BlockPos neighborPos, boolean movedByPiston) {
		super.neighborChanged(state, level, pos, neighborBlock, neighborPos, movedByPiston);
		if(level.isClientSide) return;
		BlockState updated = connect(state, level, pos);
		if(updated != state) level.setBlock(pos, updated, Block.UPDATE_CLIENTS);
	}

	/**
	 * The fluid changed: recompute, and tell the neighbours, whose own end flags read this duct's
	 * fluid (upstream redrew every frame, so it never had to).
	 */
	@Override
	public void updateConnections(Level level, BlockPos pos) {
		if(level.isClientSide) return;
		BlockState state = level.getBlockState(pos);
		BlockState updated = connect(state, level, pos);
		if(updated != state) level.setBlock(pos, updated, Block.UPDATE_CLIENTS);
		level.updateNeighborsAt(pos, this);
	}

	/// SHAPES ///

	/** Upstream's {@code getCollisionAABB}: one box around whatever the duct draws. */
	public static VoxelShape outlineFor(int mask) {
		boolean pX = (mask & 32) != 0, nX = (mask & 16) != 0;
		boolean pY = (mask & 8) != 0, nY = (mask & 4) != 0;
		boolean pZ = (mask & 2) != 0, nZ = (mask & 1) != 0;
		return switch(mask) {
			case 0 -> Shapes.box(0F, 0F, 0F, 1F, 1F, 1F);
			case 0b100000, 0b010000, 0b110000 -> Shapes.box(0F, 0.3125F, 0.3125F, 1F, 0.6875F, 0.6875F);
			case 0b001000, 0b000100, 0b001100 -> Shapes.box(0.3125F, 0F, 0.3125F, 0.6875F, 1F, 0.6875F);
			case 0b000010, 0b000001, 0b000011 -> Shapes.box(0.3125F, 0.3125F, 0F, 0.6875F, 0.6875F, 1F);
			default -> Shapes.box(
					nX ? 0F : 0.3125F,
					nY ? 0F : 0.3125F,
					nZ ? 0F : 0.3125F,
					pX ? 1F : 0.6875F,
					pY ? 1F : 0.6875F,
					pZ ? 1F : 0.6875F);
		};
	}

	@Override
	protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
		return OUTLINES[mask(state)];
	}

	@Override
	protected VoxelShape getCollisionShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
		return FluidDuctStandard.shapeFor(mask(state));
	}

	/** Upstream's "TODO: fix ts": the base mod's fluid duct item, of this duct's fluid. */
	@Override
	public ItemStack getCloneItemStack(LevelReader level, BlockPos pos, BlockState state) {
		if(level.getBlockEntity(pos) instanceof FFDuctTE pipe)
			return ItemFluidDuct.make(pipe.getFluidType());
		return getVariantStack(state);
	}

	/// LOOK OVERLAY ///

	@Override
	@OnlyIn(Dist.CLIENT)
	public void printHook(GuiGraphics gui, Level world, BlockPos pos) {
		printDuct(gui, world, pos, getDescriptionId());
	}

	/** The overlay both ducts print: the description in grey, then the fluid in its colour. */
	@OnlyIn(Dist.CLIENT)
	static void printDuct(GuiGraphics gui, Level world, BlockPos pos, String descriptionId) {
		if(!(world.getBlockEntity(pos) instanceof FFDuctTE duct)) return;
		List<String> text = new ArrayList<>();
		for(String s : I18nUtil.resolveKey("tile.ff_duct.desc").split("\\$"))
			text.add(ChatFormatting.GRAY + s);
		text.add("&[" + duct.getFluidType().getColor() + "&]" + duct.getFluidType().getLocalizedName());
		ILookOverlay.printGeneric(gui, I18nUtil.resolveKey(descriptionId), 0x00ff00, 0x004000, text);
	}
}
