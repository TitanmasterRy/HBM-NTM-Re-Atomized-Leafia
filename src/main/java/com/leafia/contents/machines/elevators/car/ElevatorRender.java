/**
 * The cabin: six style panels drawn out of one OBJ, a floor indicator, two direction arrows, a
 * button panel and the rope up to the pulley.
 *
 * <p>Upstream: {@code com/leafia/contents/machines/elevators/car/ElevatorRender.java}, 412 lines,
 * of which about 120 are the button panel written out twice — once per cabin style, differing in
 * four textures and three numbers.
 *
 * <h2>Seventeen parts, fifty-one models</h2>
 *
 * There is no {@code renderPart} here, so every (part, texture) pair upstream draws is its own
 * baked model (D-1040). Most parts take one texture; {@code WallOut} and {@code WallIn} take one
 * of two, the arrows one of two, and each of the two digit wheels one of <b>sixteen</b>. That is
 * 51 models for the S6 and 43 for the Skylift, all generated by
 * a generator script and named in {@link ElevatorModels}.
 *
 * <h2>The button panel is written once</h2>
 *
 * Upstream's two copies are identical but for the style's textures and the button quad's insets,
 * so {@link #renderButtons} takes a {@link Style} and the difference is data. That is the same
 * call D-1039 made for {@code EvFloor.call()}, for the same reason: two copies of the loop that
 * decides where a button is drawn is how the two styles come to disagree about it.
 *
 * <p><b>One thing that looks like a copy-paste slip is upstream's and is kept.</b> The Skylift's
 * fire button binds {@code S6.buttonFireOff} — the S6's texture, on a Skylift panel — and nothing
 * anywhere binds the lit one. Reproduced under D-021: it is what a player sees.
 *
 * <h2>Lighting</h2>
 *
 * Upstream calls {@code disableLighting()} around the lit arrow and both digit wheels, so they
 * glow regardless of where the cabin is. There is no lighting state to disable here; the
 * equivalent is drawing those parts at {@link LightTexture#FULL_BRIGHT} and everything else at
 * the packed light the renderer was handed.
 *
 * <p>{@code ConcurrentModificationException} is caught around the button loop upstream, with the
 * comment {@code // fuck you}. The cause is real — {@link ElevatorEntity#buttons} is rebuilt on
 * the client whenever a style changes, which can happen mid-frame — so the guard is kept, over a
 * copy of the list rather than a bare catch, which fixes the same problem without swallowing
 * anything else.
 */
@OnlyIn(Dist.CLIENT)
public class ElevatorRender extends EntityRenderer<ElevatorEntity> {

	/** Upstream's door travel: each leaf slides this far at full open. */
	private static final float DOOR_TRAVEL = 0.440625F;

	/** Upstream's text scale for a floor button's label: one sixteenth over a 13-unit cell. */
	private static final double LABEL_CELL = 9 + 4;

	private final Font font;

	public ElevatorRender(EntityRendererProvider.Context context) {
		super(context);
		this.font = context.getFont();
	}

	@Override
	public void render(ElevatorEntity cabin, float entityYaw, float partialTick, PoseStack matrix,
			MultiBufferSource buffers, int packedLight) {

		boolean hasPower = cabin.pulley != null && cabin.pulley.getPower() >= EvPulleyTE.consumption;

		matrix.pushPose();
		// Upstream's rotate(entityYaw, 0, -1, 0): a turn about the NEGATIVE Y axis.
		matrix.mulPose(Axis.YP.rotationDegrees(-entityYaw));

		renderRope(cabin, partialTick, matrix, buffers, packedLight);

		VertexConsumer buffer = buffers.getBuffer(Sheets.cutoutBlockSheet());

		ObjUtil.renderModel(ObjUtil.getModel(S6.FRAMES), matrix, buffer, packedLight, OverlayTexture.NO_OVERLAY);

		for(int i = 0; i < 6; i++) {

			String style = cabin.getDataString(ElevatorEntity.styleParams[i]);
			int side = i - 2;

			matrix.pushPose();
			if(i >= 2) matrix.mulPose(Axis.YP.rotationDegrees(90F * side));

			switch(style) {
				case "s6floor" -> {
					draw(matrix, buffer, S6.FLOOR, packedLight);
					draw(matrix, buffer, S6.FLOOR_SIDE, packedLight);
				}
				case "s6ceiling" -> {
					draw(matrix, buffer, S6.CEILING, packedLight);
					draw(matrix, buffer, S6.CEILING_SIDE, packedLight);
				}
				case "s6wall" -> {
					draw(matrix, buffer, S6.WALL_FRAMES, packedLight);
					draw(matrix, buffer, S6.WALL_OUT_FRAME, packedLight);
					draw(matrix, buffer, S6.WALL_IN_WALL, packedLight);
				}
				case "s6window" -> {
					draw(matrix, buffer, S6.WALL_FRAMES, packedLight);
					draw(matrix, buffer, S6.WALL_OUT_WINDOW, packedLight);
					draw(matrix, buffer, S6.WALL_IN_WINDOW, packedLight);
				}
				case "s6door" -> renderDoor(cabin, side, S6.STYLE, hasPower, matrix, buffers,
						buffer, packedLight);
				case "skyliftdoor" -> renderDoor(cabin, side, Skylift.STYLE, hasPower, matrix,
						buffers, buffer, packedLight);
				default -> { /* an unknown or empty style draws nothing, as upstream. */ }
			}

			matrix.popPose();
		}

		matrix.popPose();
	}

	/**
	 * The rope from the cabin's roof up to its pulley.
	 *
	 * <p>Upstream builds the difference in world space and draws it inside the yaw-rotated matrix,
	 * exactly as {@code EvWeightRender} does — see {@code EvWeightRender}'s note; the skew is
	 * upstream's and is kept.
	 */
	private static void renderRope(ElevatorEntity cabin, float partialTick, PoseStack matrix,
			MultiBufferSource buffers, int packedLight) {

		if(cabin.pulley == null) return;

		Vec3 anchor = new Vec3(
				cabin.xOld + (cabin.getX() - cabin.xOld) * partialTick,
				cabin.yOld + (cabin.getY() - cabin.yOld) * partialTick + 2.5,
				cabin.zOld + (cabin.getZ() - cabin.zOld) * partialTick);

		Vec3 sheave = Vec3.atLowerCornerOf(cabin.pulley.getBlockPos()).add(0.5, 0, 0.5);

		matrix.pushPose();
		matrix.translate(0D, 2.5D, 0D);
		EvRope.render(buffers, matrix, Vec3.ZERO, sheave.subtract(anchor), packedLight);
		matrix.popPose();
	}

	/** One door panel: the doors, the floor plate, the logo, the arrows, the digits, the buttons. */
	private void renderDoor(ElevatorEntity cabin, int side, Style style, boolean hasPower,
			PoseStack matrix, MultiBufferSource buffers, VertexConsumer buffer, int light) {

		draw(matrix, buffer, style.doorFrame, light);

		// Upstream: a panel with no landing behind it keeps its doors shut however open the
		// cabin's own doors are.
		float door = cabin.hasExteriorDoor(side) ? cabin.getDataFloat(ElevatorEntity.DOOR_IN) : 0F;

		matrix.pushPose();
		matrix.translate(-DOOR_TRAVEL * door, 0D, 0D);
		draw(matrix, buffer, style.doorL, light);
		matrix.popPose();

		matrix.pushPose();
		matrix.translate(DOOR_TRAVEL * door, 0D, 0D);
		draw(matrix, buffer, style.doorR, light);
		matrix.popPose();

		draw(matrix, buffer, style.doorFloor, light);
		draw(matrix, buffer, style.logo, light);

		// The Skylift carries two extra plates the S6 has no object for. Asked of the style
		// rather than taken as a flag, so it cannot disagree with which style is being drawn.
		if(style == Skylift.STYLE) {
			draw(matrix, buffer, Skylift.NAME, light);
			draw(matrix, buffer, Skylift.SKYLIFT, light);
		}

		int dir = cabin.getDataInteger(ElevatorEntity.ARROW);

		boolean up = dir == 1 && hasPower;
		draw(matrix, buffer, up ? style.arrowUpOn : style.arrowUpOff,
				up ? LightTexture.FULL_BRIGHT : light);

		boolean down = dir == -1 && hasPower;
		draw(matrix, buffer, down ? style.arrowDnOn : style.arrowDnOff,
				down ? LightTexture.FULL_BRIGHT : light);

		renderFloorDisplay(cabin, style, hasPower, matrix, buffer);

		ElevatorPanelBase panel = cabin.getPanel(side);
		if(panel != null) renderButtons(cabin, panel, style, matrix, buffers, light);
	}

	/**
	 * The two-character floor readout.
	 *
	 * <p>Upstream right-pads the display to two characters by prepending spaces <b>twice</b>, so
	 * a one-character display becomes {@code " 3"} and an empty one {@code "  "} — the second
	 * call is what handles the empty case, not a duplicate. Reproduced as one loop.
	 *
	 * <p>With no power it shows two blanks rather than going dark, which is upstream's: the wheel
	 * is mechanical and a blank is a real position on it.
	 */
	private static void renderFloorDisplay(ElevatorEntity cabin, Style style, boolean hasPower,
			PoseStack matrix, VertexConsumer buffer) {

		String display = cabin.getDataString(ElevatorEntity.FLOOR_DISPLAY);
		while(display.length() < 2) display = " " + display;
		if(!hasPower) display = "  ";

		draw(matrix, buffer, lookUp(style.digit0, display.substring(1, 2)), LightTexture.FULL_BRIGHT);
		draw(matrix, buffer, lookUp(style.digit10, display.substring(0, 1)), LightTexture.FULL_BRIGHT);
	}

	/** Upstream's {@code getOrDefault(key, map.get(" "))}: an unknown character reads as blank. */
	private static ModelResourceLocation lookUp(Map<String, ModelResourceLocation> wheel, String key) {
		return wheel.getOrDefault(key, wheel.get(" "));
	}

	/**
	 * The button panel: one quad per button, one per label, and text for the numbered ones.
	 *
	 * <p>{@code staticX} is in <b>sixteenths</b> and {@code staticZ} is in <b>blocks</b>, which is
	 * upstream's own mismatch and is why one is divided by 16 here and the other is not (D-1034).
	 */
	private void renderButtons(ElevatorEntity cabin, ElevatorPanelBase panel, Style style,
			PoseStack matrix, MultiBufferSource buffers, int light) {

		double staticX = panel.getStaticX() / 16D;
		double staticZ = panel.getStaticZ();

		// Upstream catches ConcurrentModificationException around this loop; a copy is the same
		// guard without swallowing anything else. The list is rebuilt client-side on a style
		// change, which can land mid-frame.
		for(ElevatorButton button : new ArrayList<>(cabin.buttons)) {

			double x = staticX + button.x / 16D;
			double y = button.y / 16D;

			if(button instanceof FireButton) {
				// Upstream binds the S6's fire texture for BOTH styles; see the class javadoc.
				quad(buffers, matrix, S6.BUTTON_FIRE_OFF, light,
						x - 1 / 16D, y - 0.2 / 16D, x + 1 / 16D, y + 1.2 / 16D, -staticZ);
				continue;
			}

			boolean lit = cabin.enabledButtons.contains(button.id)
					|| cabin.clickedButtons.containsKey(button.id);
			quad(buffers, matrix, lit ? style.buttonOn : style.buttonOff, light,
					x + style.buttonLow / 16D, y + style.buttonLow / 16D,
					x + style.buttonHigh / 16D, y + style.buttonHigh / 16D, -staticZ);

			quad(buffers, matrix, style.buttonLabel, light,
					x + style.labelLeft / 16D, y,
					x + style.labelRight / 16D, y + style.labelTop / 16D, -staticZ);

			if(button instanceof FloorButton floor) {
				renderLabelText(floor.label, matrix, buffers, light, x + style.labelLeft / 16D,
						y + 1 / 16D, -staticZ + 0.001);
				continue;
			}

			ResourceLocation label = null;
			if(button instanceof OpenButton) label = ElevatorModels.LABEL_OPEN;
			if(button instanceof CloseButton) label = ElevatorModels.LABEL_CLOSE;
			if(button instanceof BellButton) label = ElevatorModels.LABEL_BELL;
			if(label == null) continue;

			// Upstream scales into the label cell and draws an 11x11 quad offset by (1, -1).
			matrix.pushPose();
			matrix.translate(x + style.labelLeft / 16D, y + 1 / 16D, -staticZ + 0.001);
			matrix.scale((float) (1 / 16D / LABEL_CELL), (float) (1 / 16D / LABEL_CELL),
					(float) (1 / 16D / LABEL_CELL));
			matrix.translate(1D, -1D, 0D);
			quad(buffers, matrix, label, light, 0, -11, 11, 0, 0);
			matrix.popPose();
		}
	}

	/**
	 * A floor button's number, drawn with the game's font.
	 *
	 * <p>Upstream centres it by measuring the string and shifting by half the difference, then
	 * flips it with {@code rotate(180, 1, 0, 0)} because the panel faces the other way. Both are
	 * kept; the flip is a rotation about X here rather than a GL call.
	 */
	private void renderLabelText(String text, PoseStack matrix, MultiBufferSource buffers,
			int light, double x, double y, double z) {

		if(text == null) return;

		matrix.pushPose();
		matrix.translate(x, y, z);
		float s = (float) (1 / 16D / LABEL_CELL);
		matrix.scale(s, s, s);
		matrix.translate(LABEL_CELL / 2D - font.width(text) / 2D, 0D, 0D);
		matrix.mulPose(Axis.XP.rotationDegrees(180F));

		font.drawInBatch(Component.literal(text), 0F, 3F, 0xFFFFFF, false,
				matrix.last().pose(), buffers, Font.DisplayMode.NORMAL, 0, light);

		matrix.popPose();
	}

	/** One baked part at the current matrix. */
	private static void draw(PoseStack matrix, VertexConsumer buffer, ModelResourceLocation model, int light) {
		ObjUtil.renderModel(ObjUtil.getModel(model), matrix, buffer, light, OverlayTexture.NO_OVERLAY);
	}

	/**
	 * One flat quad on a standalone texture, in upstream's vertex order.
	 *
	 * <p>Upstream winds these bottom-left, bottom-right, top-right, top-left with V flipped, which
	 * is reproduced literally — the four {@code addVertexWithUV} calls below are its four.
	 */
	private static void quad(MultiBufferSource buffers, PoseStack matrix, ResourceLocation texture,
			int light, double x0, double y0, double x1, double y1, double z) {

		LeafiaBrush brush = new LeafiaBrush().begin(buffers, matrix, texture, light).normal(0, 0, 1);
		brush.addVertexWithUV(x0, y0, z, 0, 1);
		brush.addVertexWithUV(x1, y0, z, 1, 1);
		brush.addVertexWithUV(x1, y1, z, 1, 0);
		brush.addVertexWithUV(x0, y1, z, 0, 0);
		brush.end();
	}

	@Override
	public ResourceLocation getTextureLocation(ElevatorEntity cabin) {
		// Upstream returns null; nothing asks, because every draw names its own model or texture.
		return EvRope.TEXTURE;
	}
}
