/**
 * Every addon item model that draws an OBJ sits where a block would, in every context an item is
 * drawn in (D-1081).
 *
 * <h2>Why this is pure arithmetic on the JSON</h2>
 *
 * D-1080's first screenshot found the advisor invisible in every slot and hand: its {@code
 * display} block had been derived the way the elevators' were, as {@code -centre * scale}, which
 * ignores that vanilla draws {@code T * R * S * (v - 0.5)} - the half-block shift comes before the
 * display transform and the rotation differs per context. It is right only for a model whose
 * bounding box is already centred in its cell. The elevators' items were generated by the same
 * arithmetic and were off by up to a block; nothing had looked at one in a slot.
 *
 * <p>No client is needed to check it. This reads each item's JSON, follows it (a composite's
 * children, a parent block model, a model's {@code visibility} list) to the {@code .obj} it draws,
 * takes the bounding box of the objects that are drawn, and runs the item's {@code display} block
 * through JOML in the order vanilla multiplies: translate, rotate XYZ, scale, then the shift of
 * minus a half. The middle of the box has to land where vanilla's own {@code block/block} display
 * lands the middle of a cube - the middle of the slot, a little up on the ground and in the third
 * person hand, and the raised, pulled-in point the first-person hand uses so a long model does
 * not run off the screen - and its silhouette has to be big enough to see and, in the inventory,
 * small enough for the slot.
 *
 * <p>A model with no {@code display} of its own is checked against the identity transform, which
 * is what vanilla applies when nothing up the parent chain has one.
 */
@GameTestHolder(LeafiaRef.MODID)
@PrefixGameTestTemplate(false)
public class LeafiaItemDisplayTests {

	private static final String EMPTY = "empty";

	/** Where the middle of the model belongs, in sixteenths, and how large its silhouette should be. */
	private record Context(String name, double[] home, double min, double max) { }

	private static final List<Context> CONTEXTS = List.of(
			new Context("gui", new double[] {0, 0, 0}, 0.30, 1.0),
			new Context("ground", new double[] {0, 3, 0}, 0.12, 0.6),
			new Context("fixed", new double[] {0, 0, 0}, 0.25, 1.0),
			new Context("thirdperson_righthand", new double[] {0, 2.5, 0}, 0.2, 0.9),
			new Context("firstperson_righthand", new double[] {-3, 7, 0}, 0.2, 0.8));

	/**
	 * The models whose {@code display} is upstream's own knobs rather than the shared formula: a scale
	 * of {@code _sizeReference / extent} and a lift, in vanilla's block rotations. Their silhouettes
	 * are right and their middles are within a sixth of a block of the mark; the first-person mark is
	 * the raised, pulled-in point the formula uses for long models, which a cube-like machine has no
	 * need of, so it is not asked of them.
	 */
	// heater_rt carries the base mod's own oil-burner display, the same OBJ (D-3020)
	private static final Set<String> KNOBS = Set.of("broof", "hp_boiler", "modular_turbine_core", "heater_rt");

	/**
	 * The advisor with its lid up: the lid swings out past the body about its hinge, so the box is
	 * wider than the closed one and the item shares the closed one's display, by design (D-1080), so
	 * that opening it does not move it in the hand. It may stick out of the slot; it may not leave it.
	 */
	private static final String OPEN_LID = "advisor_open";

	// ---- resources ----

	private static String text(String path) {
		try(InputStream in = LeafiaItemDisplayTests.class.getResourceAsStream("/assets/leafia/" + path)) {
			if(in == null) return null;
			return new String(in.readAllBytes(), StandardCharsets.UTF_8);
		} catch(IOException e) {
			throw new IllegalStateException(e);
		}
	}

	/** A resource of another namespace, {@code ns:path}, off the classpath; null when absent. */
	private static String foreignText(String ref) {
		int colon = ref.indexOf(':');
		if(colon < 0) return null;
		// the base mod's resources are in its own module, so read them through one of its classes
		Class<?> owner = ref.startsWith("hbm:") ? com.hbm.blocks.ModBlocks.class : LeafiaItemDisplayTests.class;
		try(InputStream in = owner.getResourceAsStream("/assets/" + ref.substring(0, colon) + "/" + ref.substring(colon + 1))) {
			if(in == null) return null;
			return new String(in.readAllBytes(), StandardCharsets.UTF_8);
		} catch(IOException e) {
			throw new IllegalStateException(e);
		}
	}

	private static JsonObject json(String path) {
		String t = text(path);
		return t == null ? null : JsonParser.parseString(t).getAsJsonObject();
	}

	/** Every file name under {@code models/item}, without its extension. */
	private static List<String> itemModels() {
		try {
			URI uri = LeafiaItemDisplayTests.class.getResource("/assets/leafia/models/item").toURI();
			try(Stream<Path> files = Files.list(Path.of(uri))) {
				return files.map(p -> p.getFileName().toString()).filter(n -> n.endsWith(".json"))
						.map(n -> n.substring(0, n.length() - 5)).sorted().toList();
			}
		} catch(Exception e) {
			throw new IllegalStateException("could not list models/item", e);
		}
	}

	private static String local(String ref) {
		return ref != null && ref.startsWith("leafia:") ? ref.substring("leafia:".length()) : null;
	}

	// ---- geometry ----

	/** The box of the objects of an .obj that are not hidden, or null when the model draws none. */
	private static double[][] objBox(String ref, Set<String> hidden) {
		// An addon model may name another mod's OBJ - the RT heater draws the base mod's oil burner (D-3020).
		String obj = local(ref) != null ? local(ref) : ref;
		String t = local(ref) != null ? text(obj) : foreignText(ref);
		if(t == null) throw new IllegalStateException("missing .obj " + obj);
		double[] lo = {Double.MAX_VALUE, Double.MAX_VALUE, Double.MAX_VALUE};
		double[] hi = {-Double.MAX_VALUE, -Double.MAX_VALUE, -Double.MAX_VALUE};
		String current = null;
		boolean any = false;
		for(String line : t.split("\n")) {
			if(line.startsWith("o ") || line.startsWith("g ")) current = line.substring(2).trim();
			else if(line.startsWith("v ") && !hidden.contains(current)) {
				String[] f = line.trim().split("\\s+");
				for(int i = 0; i < 3; i++) {
					double v = Double.parseDouble(f[i + 1]);
					lo[i] = Math.min(lo[i], v);
					hi[i] = Math.max(hi[i], v);
				}
				any = true;
			}
		}
		return any ? new double[][] {lo, hi} : null;
	}

	/** What a block model draws, following its parents: an OBJ box, or null for anything else. */
	private static double[][] blockBox(String model, int depth) {
		JsonObject d = json("models/" + model + ".json");
		if(d == null || depth > 6) return null;
		if(d.has("loader") && d.get("loader").getAsString().equals("neoforge:obj")) {
			Set<String> hidden = new HashSet<>();
			if(d.has("visibility"))
				for(Map.Entry<String, JsonElement> e : d.getAsJsonObject("visibility").entrySet())
					if(!e.getValue().getAsBoolean()) hidden.add(e.getKey());
			return objBox(d.get("model").getAsString(), hidden);
		}
		if(d.has("loader") && d.get("loader").getAsString().equals("neoforge:composite")) {
			double[] lo = {Double.MAX_VALUE, Double.MAX_VALUE, Double.MAX_VALUE};
			double[] hi = {-Double.MAX_VALUE, -Double.MAX_VALUE, -Double.MAX_VALUE};
			boolean any = false;
			for(Map.Entry<String, JsonElement> e : d.getAsJsonObject("children").entrySet()) {
				JsonObject child = e.getValue().getAsJsonObject();
				String parent = child.has("parent") ? local(child.get("parent").getAsString()) : null;
				double[][] box = parent == null ? null : blockBox(parent, depth + 1);
				if(box == null) continue;
				any = true;
				for(int i = 0; i < 3; i++) {
					lo[i] = Math.min(lo[i], box[0][i]);
					hi[i] = Math.max(hi[i], box[1][i]);
				}
			}
			return any ? new double[][] {lo, hi} : null;
		}
		String parent = d.has("parent") ? local(d.get("parent").getAsString()) : null;
		return parent == null ? null : blockBox(parent, depth + 1);
	}

	/** The box an item draws: a composite is the union of its children, else its parent block model. */
	private static double[][] itemBox(JsonObject item) {
		if(item.has("loader") && item.get("loader").getAsString().equals("neoforge:composite")) {
			double[] lo = {Double.MAX_VALUE, Double.MAX_VALUE, Double.MAX_VALUE};
			double[] hi = {-Double.MAX_VALUE, -Double.MAX_VALUE, -Double.MAX_VALUE};
			boolean any = false;
			for(Map.Entry<String, JsonElement> e : item.getAsJsonObject("children").entrySet()) {
				JsonObject child = e.getValue().getAsJsonObject();
				String parent = child.has("parent") ? local(child.get("parent").getAsString()) : null;
				double[][] box = parent == null ? null : blockBox(parent, 0);
				if(box == null) continue;
				any = true;
				for(int i = 0; i < 3; i++) {
					lo[i] = Math.min(lo[i], box[0][i]);
					hi[i] = Math.max(hi[i], box[1][i]);
				}
			}
			return any ? new double[][] {lo, hi} : null;
		}
		String parent = item.has("parent") ? local(item.get("parent").getAsString()) : null;
		return parent != null && parent.startsWith("block/") ? blockBox(parent, 0) : null;
	}

	private static double[] triple(JsonObject d, String key, double fallback) {
		if(d == null || !d.has(key)) return new double[] {fallback, fallback, fallback};
		JsonArray a = d.getAsJsonArray(key);
		return new double[] {a.get(0).getAsDouble(), a.get(1).getAsDouble(), a.get(2).getAsDouble()};
	}

	/** Where one context's display block puts the box: the middle of it, and its silhouette's width and height. */
	private static double[] place(double[][] box, JsonObject d, boolean identity) {
		double[] t = identity ? new double[] {0, 0, 0} : triple(d, "translation", 0);
		double[] r = identity ? new double[] {0, 0, 0} : triple(d, "rotation", 0);
		double[] s = identity ? new double[] {1, 1, 1} : triple(d, "scale", 1);
		org.joml.Matrix4f m = new org.joml.Matrix4f()
				.translate((float) (t[0] / 16), (float) (t[1] / 16), (float) (t[2] / 16))
				.rotateXYZ((float) Math.toRadians(r[0]), (float) Math.toRadians(r[1]), (float) Math.toRadians(r[2]))
				.scale((float) s[0], (float) s[1], (float) s[2])
				.translate(-0.5f, -0.5f, -0.5f);
		double minX = Double.MAX_VALUE, maxX = -Double.MAX_VALUE, minY = Double.MAX_VALUE, maxY = -Double.MAX_VALUE;
		for(int k = 0; k < 8; k++) {
			org.joml.Vector3f c = m.transformPosition(new org.joml.Vector3f(
					(float) box[(k & 1)][0], (float) box[(k >> 1) & 1][1], (float) box[(k >> 2) & 1][2]));
			minX = Math.min(minX, c.x);
			maxX = Math.max(maxX, c.x);
			minY = Math.min(minY, c.y);
			maxY = Math.max(maxY, c.y);
		}
		org.joml.Vector3f middle = m.transformPosition(new org.joml.Vector3f(
				(float) ((box[0][0] + box[1][0]) / 2), (float) ((box[0][1] + box[1][1]) / 2), (float) ((box[0][2] + box[1][2]) / 2)));
		return new double[] {middle.x, middle.y, middle.z, maxX - minX, maxY - minY, (minX + maxX) / 2, (minY + maxY) / 2};
	}

	/**
	 * Every problem with where {@code name}'s display puts its model, empty when it sits right.
	 * An item with no OBJ geometry is not this test's business and returns empty.
	 */
	private static List<String> problems(String name) {
		JsonObject item = json("models/item/" + name + ".json");
		double[][] box = itemBox(item);
		List<String> out = new ArrayList<>();
		if(box == null) return out;
		JsonObject display = item.has("display") ? item.getAsJsonObject("display") : null;
		for(Context c : CONTEXTS) {
			JsonObject d = display != null && display.has(c.name) ? display.getAsJsonObject(c.name) : null;
			// Left hands repeat the right's values, which vanilla's deserializer does too.
			double[] p = place(box, d, d == null);
			double off = 0;
			for(int i = 0; i < 3; i++) off = Math.max(off, Math.abs(p[i] - c.home[i] / 16));
			double size = Math.max(p[3], p[4]);
			boolean knob = KNOBS.contains(name);
			double allowed = name.equals(OPEN_LID) ? 0.3 : knob ? 0.2 : 0.02;
			if(off > allowed && !(knob && c.name.equals("firstperson_righthand")))
				out.add(c.name + ": the middle of the model lands " + String.format("%.3f", off) + " blocks from its mark");
			double max = name.equals(OPEN_LID) ? c.max * 1.5 : c.max;
			if(size < c.min || size > max)
				out.add(c.name + ": the silhouette is " + String.format("%.3f", size) + " blocks, expected " + c.min + " to " + max);
			if(c.name.equals("gui") && !name.equals(OPEN_LID) && (Math.abs(p[5]) + p[3] / 2 > 0.5 + 1e-3 || Math.abs(p[6]) + p[4] / 2 > 0.5 + 1e-3))
				out.add("gui: the box leaves the slot, x " + String.format("%.2f", p[5] - p[3] / 2) + ".." + String.format("%.2f", p[5] + p[3] / 2)
						+ " y " + String.format("%.2f", p[6] - p[4] / 2) + ".." + String.format("%.2f", p[6] + p[4] / 2));
		}
		return out;
	}

	private static void check(GameTestHelper helper, String family, Predicate<String> in) {
		List<String> bad = new ArrayList<>();
		int seen = 0;
		for(String name : itemModels()) {
			if(!in.test(name)) continue;
			JsonObject item = json("models/item/" + name + ".json");
			if(itemBox(item) == null) continue;
			seen++;
			List<String> p = problems(name);
			if(!p.isEmpty()) bad.add(name + " - " + String.join("; ", p));
		}
		helper.assertTrue(seen > 0, family + ": no item model matched, so nothing was checked");
		helper.assertTrue(bad.isEmpty(), family + ": " + bad.size() + " of " + seen + " misplaced: " + bad);
		helper.succeed();
	}

	// ---- the families ----

	/** The one the advisor's own test pins, from the other side: through the shared checker. */
	@GameTest(template = EMPTY)
	public static void theAdvisorSitsInEveryContext(GameTestHelper helper) {
		check(helper, "advisor", n -> n.startsWith("advisor"));
	}

	/**
	 * The elevators' items: the buffer, pulley, the two floor styles, the seven cabin parts and the
	 * counterweight. Generated by the formula that ignored the half-block shift, they sat up to
	 * 1.3 blocks off their marks and the cabin panels left the inventory slot altogether.
	 */
	@GameTest(template = EMPTY)
	public static void theElevatorItemsSitInEveryContext(GameTestHelper helper) {
		check(helper, "elevator", n -> n.startsWith("elevator_") || n.startsWith("ev_") || n.equals("weight_spawn"));
	}

	/** Whatever else draws an OBJ: if a family is added or regenerated, it is held to the same standard. */
	@GameTest(template = EMPTY)
	public static void everyOtherObjItemSitsInEveryContext(GameTestHelper helper) {
		check(helper, "other", n -> !(n.startsWith("advisor") || n.startsWith("elevator_") || n.startsWith("ev_") || n.equals("weight_spawn")));
	}

	/**
	 * The letter signs are drawn by a {@code BlockEntityWithoutLevelRenderer}, so there is no OBJ to
	 * measure; what the model owns is how much of the slot the letter fills. The letter is one block
	 * tall by construction (seven glyph rows at one seventh), so the slot shows it a little under
	 * full size and no larger, or it runs into its neighbours (D-1081). All thirty-six letters share
	 * the one model.
	 */
	@GameTest(template = EMPTY)
	public static void theLetterSignsFitTheSlotAndShareOneModel(GameTestHelper helper) {
		JsonObject shared = json("models/item/letter_sign.json");
		JsonObject display = shared.getAsJsonObject("display");
		for(Context c : CONTEXTS) {
			if(!display.has(c.name)) continue;
			double s = display.getAsJsonObject(c.name).getAsJsonArray("scale").get(0).getAsDouble();
			helper.assertTrue(s > 0 && s <= 1.0 + 1e-9, c.name + ": the letter is one block tall, so a scale of " + s + " would overflow");
		}
		double gui = display.getAsJsonObject("gui").getAsJsonArray("scale").get(0).getAsDouble();
		helper.assertTrue(gui >= 0.6 && gui < 1.0, "the slot leaves the letter a margin: " + gui);
		int letters = 0;
		for(String name : itemModels()) {
			if(!name.startsWith("letter_sign_")) continue;
			letters++;
			helper.assertTrue("leafia:item/letter_sign".equals(json("models/item/" + name + ".json").get("parent").getAsString()),
					name + " does not share the one sign model");
		}
		helper.assertTrue(letters == 36, "36 letter signs, found " + letters);
		helper.succeed();
	}

	/** The checker itself, against a case with a known answer: a unit cube under vanilla's own block display. */
	@GameTest(template = EMPTY)
	public static void theCheckerAgreesWithVanillaOnACube(GameTestHelper helper) {
		double[][] cube = {{0, 0, 0}, {1, 1, 1}};
		JsonObject gui = JsonParser.parseString("{\"rotation\":[30,225,0],\"translation\":[0,0,0],\"scale\":[0.625,0.625,0.625]}").getAsJsonObject();
		double[] p = place(cube, gui, false);
		helper.assertTrue(Math.abs(p[0]) < 1e-4 && Math.abs(p[1]) < 1e-4 && Math.abs(p[2]) < 1e-4, "a cube's middle is at the origin: " + p[0] + "," + p[1] + "," + p[2]);
		// 0.625 * (sqrt(2)) wide at 45 degrees, and a little taller at 30 degrees of pitch.
		helper.assertTrue(Math.abs(p[3] - 0.625 * Math.sqrt(2)) < 0.01, "silhouette width " + p[3]);
		Set<String> names = new TreeSet<>(itemModels());
		helper.assertTrue(names.contains("advisor") && names.contains("ev_s6door"), "the item model listing is not empty of what this test is about");
		helper.succeed();
	}
}
