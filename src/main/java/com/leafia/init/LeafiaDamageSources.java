package com.leafia.init;

import com.leafia.lib.LeafiaRef;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.damagesource.DamageType;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.Level;

/**
 * Ported from `com.leafia.init.LeafiaDamageSource`.
 *
 * <p>Every way the addon can kill you. Upstream builds 14 ready-made {@code DamageSource}
 * objects and flips booleans on them; a damage type is a datapack registry entry in 1.21.1
 * and the booleans are tags, so the objects become keys and a source is built from a key and
 * a {@link Level} when it is needed - resolving a key needs the registries a level carries.
 * This is the same shape the base mod's {@code ModDamageSource} took, for the same reasons;
 * see D-025 for the flag-to-tag mapping and D-1010 for the two flags the addon
 * uses that the base mod's 1.7.10 source did not.
 *
 * <p><b>Generated by a script</b> - do not edit by hand. Which damage
 * ignores armour is balance, and a wrong flag is invisible until somebody survives a hit they
 * should not have.
 *
 * <p>Registry path and message id differ on purpose: a path must be lowercase, while the
 * message id is what {@code death.attack.<id>} keys on and so keeps upstream's camelCase.
 */
public class LeafiaDamageSources {

	public static final ResourceKey<DamageType> fleija = key("fleija"); // bypasses_armor
	public static final ResourceKey<DamageType> back = key("back"); // bypasses_armor, bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_invulnerability
	public static final ResourceKey<DamageType> mine = key("mine"); // is_explosion, bypasses_armor
	public static final ResourceKey<DamageType> dfc = key("dfc"); // bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor
	public static final ResourceKey<DamageType> dfcMeltdown = key("dfc_meltdown"); // bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor, bypasses_invulnerability
	public static final ResourceKey<DamageType> pointed = key("pointed");
	public static final ResourceKey<DamageType> poison = key("poison"); // bypasses_invulnerability, bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor
	public static final ResourceKey<DamageType> drinkcryo = key("drinkcryo"); // bypasses_invulnerability, bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor
	public static final ResourceKey<DamageType> drinkhot = key("drinkhot"); // bypasses_invulnerability, bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor, is_fire
	public static final ResourceKey<DamageType> drinkacid = key("drinkacid"); // bypasses_invulnerability, bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor, is_fire
	public static final ResourceKey<DamageType> flywheel = key("flywheel"); // bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor
	public static final ResourceKey<DamageType> mine_player = key("mine_player"); // bypasses_effects, bypasses_enchantments, bypasses_resistance
	public static final ResourceKey<DamageType> am_rifle = key("am_rifle"); // bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_invulnerability, bypasses_armor, witch_resistant_to
	public static final ResourceKey<DamageType> pillMeltdown = key("pill_meltdown"); // bypasses_invulnerability, bypasses_effects, bypasses_enchantments, bypasses_resistance, bypasses_armor
	public static final ResourceKey<DamageType> cryo = key("cryo");
	public static final ResourceKey<DamageType> endothermic = key("endothermic"); // bypasses_armor, witch_resistant_to, is_explosion

	private static ResourceKey<DamageType> key(String name) {
		return ResourceKey.create(Registries.DAMAGE_TYPE, LeafiaRef.rl(name));
	}

	/** Builds a usable source. The registries come from the level, so this needs one. */
	public static DamageSource of(Level level, ResourceKey<DamageType> type) {
		return new DamageSource(level.registryAccess().registryOrThrow(Registries.DAMAGE_TYPE).getHolderOrThrow(type));
	}

	/** As above, with an attacker and the entity that actually delivered it. */
	public static DamageSource of(Level level, ResourceKey<DamageType> type, Entity direct, Entity attacker) {
		return new DamageSource(level.registryAccess().registryOrThrow(Registries.DAMAGE_TYPE).getHolderOrThrow(type), direct, attacker);
	}
}
